export function toast(msg, type = '') {
  const el = document.createElement('div');
  el.className = 'toast ' + type; el.textContent = msg;
  $('#toasts').append(el);
  setTimeout(() => { el.style.transition = 'opacity .3s'; el.style.opacity = 0; setTimeout(() => el.remove(), 300); }, type === 'err' ? 5200 : 2800);
}

export function modal({ title, body, size = '', buttons = [], onClose }) {
  const ov = document.createElement('div');
  ov.className = 'overlay';
  ov.innerHTML = `<div class="modal ${size}" role="dialog" aria-modal="true"><div class="modal-h"><h2>${esc(title)}</h2><button class="btn btn-ghost icon-btn" data-x aria-label="Đóng">${ICON.x}</button></div><div class="modal-b"></div><div class="modal-f"></div></div>`;
  const b = $('.modal-b', ov); typeof body === 'string' ? (b.innerHTML = body) : b.append(body);
  const close = () => { ov.remove(); document.removeEventListener('keydown', onKey); onClose?.(); };
  const onKey = (e) => { if (e.key === 'Escape') close(); };
  document.addEventListener('keydown', onKey);
  const foot = $('.modal-f', ov);
  buttons.forEach((bt) => {
    const el = document.createElement('button'); el.className = 'btn ' + (bt.cls || ''); el.innerHTML = bt.label;
    el.onclick = async () => {
      if (bt.close) return close();
      el.disabled = true;
      try { const r = await bt.onClick?.(ov, close); if (r !== false) close(); } catch (e) { toast(e.message || String(e), 'err'); }
      el.disabled = false;
    };
    foot.append(el);
  });
  if (!buttons.length) foot.remove();
  $('[data-x]', ov).onclick = close;
  ov.addEventListener('mousedown', (e) => { if (e.target === ov) close(); });
  document.body.append(ov);
  const first = $('input,select,textarea', ov); first?.focus();
  return { el: ov, close };
}

export function confirmBox(message, okLabel = 'Xác nhận', danger = true) {
  return new Promise((res) => {
    modal({ title: 'Xác nhận', size: 'sm', body: `<p style="margin:0">${esc(message)}</p>`, onClose: () => res(false),
      buttons: [{ label: 'Hủy', close: true }, { label: okLabel, cls: danger ? 'btn-danger' : 'btn-primary', onClick: (_o, close) => { res(true); return true; } }] });
  });
}

